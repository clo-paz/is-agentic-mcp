const assert = require('node:assert/strict');
const {execFileSync} = require('node:child_process');
const account = '1'.repeat(12);
const template = JSON.parse(execFileSync('node', ['node_modules/aws-cdk/bin/cdk', 'synth', 'is-agentic-mcp-url', '--json'], {encoding: 'utf8', env: {...process.env, CDK_DEFAULT_ACCOUNT: account, MCP_BOUNDARY_POLICY_ARN: `arn:aws:iam::${account}:policy/DeploymentBoundary`}}));
const resources = Object.values(template.Resources);
const ofType = type => resources.filter(r => r.Type === type);
assert.equal(ofType('AWS::Lambda::Function').length, 1);
assert.equal(ofType('AWS::Lambda::Url').length, 1);
assert.equal(ofType('AWS::IAM::Role').length, 1);
assert.equal(ofType('AWS::Route53::RecordSet').length, 0);
assert.equal(ofType('AWS::CertificateManager::Certificate').length, 0);
assert.equal(ofType('AWS::ApiGatewayV2::Api').length, 0);
assert.equal(ofType('AWS::EC2::VPC').length, 0);
assert.equal(ofType('AWS::DynamoDB::Table').length, 0);
const fn = ofType('AWS::Lambda::Function')[0].Properties;
assert.equal(fn.Runtime, 'nodejs20.x');
assert.equal(fn.Handler, 'handler.handler');
assert.equal(fn.ReservedConcurrentExecutions, 5);
assert.equal(fn.Timeout, 10);
assert.equal(fn.Role['Fn::GetAtt'][0].includes('McpExecutionRole'), true);
const role = ofType('AWS::IAM::Role')[0].Properties;
assert.equal(role.RoleName, 'is-agentic-mcp-execution');
assert.match(JSON.stringify(role.PermissionsBoundary), /DeploymentBoundary/);
assert.equal(role.ManagedPolicyArns, undefined);
const policies = ofType('AWS::IAM::Policy');
assert.equal(policies.length, 1);
const statements = policies[0].Properties.PolicyDocument.Statement;
assert.equal(statements.length, 1);
assert.deepEqual(statements[0].Action, ['logs:CreateLogStream', 'logs:PutLogEvents']);
assert.match(JSON.stringify(statements[0].Resource), /log-group:\/aws\/lambda\/is-agentic-mcp:\*/);
const url = ofType('AWS::Lambda::Url')[0].Properties;
assert.equal(url.AuthType, 'NONE');
assert.deepEqual(url.Cors.AllowMethods, ['GET', 'POST']);
assert.equal(url.Cors.AllowOrigins[0], '*');
const alarms = ofType('AWS::CloudWatch::Alarm');
assert.equal(alarms.length, 3);
assert.equal(alarms.find(a => a.Properties.AlarmName === 'is-agentic-mcp-5xx').Properties.MetricName, 'Url5xxCount');
console.log('Isolated Function URL synth, role, boundary, CORS, alarms, and absence of DNS/VPC/database verified');
