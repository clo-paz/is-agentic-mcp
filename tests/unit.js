const originalFetch = global.fetch;
const paths = [];
const item = (id, title, available=true) => ({title,handle:title.toLowerCase().replaceAll(' ','-'),body_html:'A thoughtful gift',product_type:'Mug',tags:['series-test'],variants:[{id,title:'Default',price:'18.00',available}],images:[{src:'https://cdn.shopify.com/image.jpg',alt:'Mug'}]});
