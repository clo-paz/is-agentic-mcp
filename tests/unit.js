global.fetch = async (url, options) => {
  const u = new URL(url);
  assert.equal(u.origin, 'https://is-agentic.shop');
  assert.equal(options.redirect, 'manual');
  assert.equal(options.method, undefined);
  paths.push(u.pathname+u.search);
  let data;
  if (u.pathname==='/products.json') data={products:u.searchParams.get('page')==='1'?products:[]};
  else if (u.pathname==='/collections.json') data={collections:[{title:'For Your Human',handle:'for-your-human',products_count:2}]};
  else if (u.pathname==='/products/blue-mug.json') data={product:products[0]};
  else if (u.pathname==='/collections/for-your-human/products.json') data={products:u.searchParams.get('page')==='1'?Array(250).fill(products[0]):u.searchParams.get('page')==='2'?[products[1]]:[]};
  else if (u.pathname==='/.well-known/mcp.json') data={name:'is-agentic'};
  else if (u.pathname==='/.well-known/ai-catalog.json') data={products};
  else throw Error('Unexpected fetch: '+url);
  return {ok:true,headers:new Headers(),text:async()=>JSON.stringify(data)};
};
